// Generates ../THIRD_PARTY_NOTICES.md: the licenses of everything bundled into
// the web UI (npm production dependencies, including the Inter, JetBrains Mono
// and KaTeX fonts). Python dependencies keep their license files in the
// image's site-packages and are listed by name.
//
//   node scripts/notices.mjs          # write the file
//   node scripts/notices.mjs --check  # CI: fail if it is out of date
import { execSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");
const out = path.resolve(root, "..", "THIRD_PARTY_NOTICES.md");

const dirs = execSync("npm ls --omit=dev --all --parseable", { cwd: root, encoding: "utf8" }).trim().split("\n").slice(1);
const packages = new Map();
for (const dir of dirs) {
  const pkg = JSON.parse(readFileSync(path.join(dir, "package.json"), "utf8"));
  const key = `${pkg.name}@${pkg.version}`;
  if (packages.has(key)) continue;
  const licenseFile = readdirSync(dir).find((f) => /^(licen[cs]e|copying|notice)(\.|$)/i.test(f));
  packages.set(key, {
    name: pkg.name,
    version: pkg.version,
    license: typeof pkg.license === "string" ? pkg.license : (pkg.license?.type ?? "see text"),
    homepage: pkg.homepage ?? (typeof pkg.repository === "string" ? pkg.repository : pkg.repository?.url) ?? "",
    text: licenseFile ? readFileSync(path.join(dir, licenseFile), "utf8").trim() : "",
  });
}

const python = [
  ["fastapi", "MIT"], ["starlette", "BSD-3-Clause"], ["uvicorn", "BSD-3-Clause"], ["pydantic", "MIT"],
  ["httpx", "BSD-3-Clause"], ["httpcore", "BSD-3-Clause"], ["python-multipart", "Apache-2.0"], ["pypdf", "BSD-3-Clause"],
  ["numpy", "BSD-3-Clause"], ["argon2-cffi", "MIT"], ["cryptography", "Apache-2.0 OR BSD-3-Clause"],
  ["trafilatura", "Apache-2.0"], ["lxml", "BSD-3-Clause"], ["charset-normalizer", "MIT"],
  ["playwright (browser image)", "Apache-2.0"], ["Chromium (browser image, via the Playwright base image)", "BSD-3-Clause and others"],
];

const sorted = [...packages.values()].sort((a, b) => a.name.localeCompare(b.name));
let md = `# Third-party notices

Chimera is MIT-licensed (see LICENSE). It includes or depends on the software
below. This file is generated by \`frontend/scripts/notices.mjs\`; do not edit it
by hand.

## Bundled in the web UI (${sorted.length} packages)

| Package | Version | License |
| --- | --- | --- |
${sorted.map((p) => `| ${p.name} | ${p.version} | ${p.license} |`).join("\n")}

## Python runtime dependencies

Installed in the Chimera image with their own license files
(\`/usr/local/lib/python3.12/site-packages/*/licenses\` or \`*.dist-info\`).

| Package | License |
| --- | --- |
${python.map(([n, l]) => `| ${n} | ${l} |`).join("\n")}

## License texts of the bundled packages

`;
for (const p of sorted) {
  md += `### ${p.name} ${p.version} (${p.license})\n\n`;
  md += p.text ? "```\n" + p.text.replaceAll("```", "ʼʼʼ") + "\n```\n\n" : `License: ${p.license}. ${p.homepage}\n\n`;
}

if (process.argv.includes("--check")) {
  const current = existsSync(out) ? readFileSync(out, "utf8") : "";
  if (current !== md) {
    console.error("THIRD_PARTY_NOTICES.md is out of date: run `node frontend/scripts/notices.mjs`.");
    process.exit(1);
  }
  console.log("THIRD_PARTY_NOTICES.md is up to date.");
} else {
  writeFileSync(out, md);
  console.log(`Wrote ${out} (${sorted.length} packages).`);
}
